const by = (a) => Object.fromEntries(a.map((x) => [x.id, x]));

export const CONFIG = config;
// A v3 file is {key: [...]} (the content lane may name the key differently): take the first array found.
const list = (o, ...keys) => (keys.map((k) => o?.[k]).find(Array.isArray) ?? Object.values(o || {}).find(Array.isArray) ?? []);
export const SYMBOLS = [...symbols.symbols, ...list(symbolsV3, 'symbols')];
export const SYM = by(SYMBOLS);
export const SCORING = SYMBOLS.filter((s) => s.kind === 'score').map((s) => s.id);
export const PATTERN_DATA = patterns.patterns;
export const CHARMS = [...charms.charms, ...list(charmsV3, 'charms')];
export const CHARM = by(CHARMS);
export const DEALS = deals.deals;
export const DEAL = by(DEALS);
export const CURSES = [...curses.curses, ...list(cursesV3, 'curses')];
export const CURSE = by(CURSES);
export const TRICKS = tricks.tricks;
export const TRICK = by(TRICKS);
export const STAKES = stakes.stakes;
export const STAKE = by(STAKES);
export const CONTRACTS = contracts.contracts;
export const CONTRACT = by(CONTRACTS);
export const CHARS = [...characters.characters, ...list(charactersV3, 'characters')];
export const CHAR = by(CHARS);
export const HIDEOUT = hideout.hideout;
export const HIDE = by(HIDEOUT);
export const ACHIEVEMENTS = achievements.achievements;
export const ACH = by(ACHIEVEMENTS);
export const BENCH = config.bench;
export const BENCH_JOB = by(BENCH);
export const RARITIES = ['common', 'uncommon', 'rare', 'legendary'];
export const rarityRank = (r) => (r === 'fused' ? RARITIES.length : RARITIES.indexOf(r)); // fused charms are never offered; they rank above legendary
export const SPIRITS = list(spirits, 'spirits');
export const SPIRIT = by(SPIRITS);
export const FUSION = fusion;
export const PLACES = list(places, 'places');
export const PLACE = by(PLACES);
export const NOTEBOOK = list(notebook, 'nodes', 'notebook', 'entries');
export const NODE = by(NOTEBOOK);
export const LOCKERS = list(lockers, 'lockers');
export const LOCKER = by(LOCKERS);
export const POSTCARDS = list(postcards, 'postcards');
export const POSTCARD = by(POSTCARDS);
export const LESSONS = list(lessons, 'lessons');
export const MILESTONES = list(milestones, 'milestones');
export const STORMS = list(storm, 'storms', 'levels');
export const FAMILIES = config.families.map((f) => f.id);
export const familyOf = (id) => CHARM[id].family ?? CHARM[id].tags.find((t) => FAMILIES.includes(t));
